export type VocabularyCategory = (typeof vocabularyCategories)[number];
export const jlptVocabularyLevels = ["N5", "N4", "N3", "N2", "N1"] as const;
export type JlptVocabularyLevel = (typeof jlptVocabularyLevels)[number];
export type VocabularyLevel = "入门" | "基础" | "进阶入门" | JlptVocabularyLevel;
type ExamVocabularyLevel = JlptVocabularyLevel;

export interface VocabularyItem {
  id: string;
  category: VocabularyCategory;
  japanese: string;
  kana: string;
  romaji: string;
  meaning: string;
  sentence: string;
  sentenceKana: string;
  translation: string;
  level?: VocabularyLevel;
  tags?: string[];
  sortOrder?: number;
  audioText?: string;
}

export const getVocabularyJlptLevel = (word: VocabularyItem): JlptVocabularyLevel => {
  if (word.level && (jlptVocabularyLevels as readonly string[]).includes(word.level)) {
    return word.level as JlptVocabularyLevel;
  }

  if (word.level === "基础" || word.level === "进阶入门") {
    return "N4";
  }

  return "N5";
};

